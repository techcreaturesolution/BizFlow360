"use client";

import React, { useState, useEffect, useCallback, useRef } from "react";
import Link from "next/link";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import {
  Search,
  Plus,
  Filter,
  Eye,
  RefreshCw,
  Building2,
  Globe,
  User,
  Mail,
  Phone,
  Lock,
  ChevronLeft,
  ChevronRight,
  AlertCircle,
  CheckCircle2,
  X,
  CreditCard,
} from "lucide-react";

import {
  getTenants,
  createTenant,
  parsePlatformError,
} from "@/lib/platform";
import type {
  PageMeta,
  TenantListItem,
  TenantStatus,
} from "@/types/platform";
import {
  createTenantSchema,
  type CreateTenantFormData,
  TENANT_STATUSES,
} from "@/lib/validations";
import { PlanSelect } from "@/components/super-admin/PlanSelect";
import { StatusBadge } from "@/components/super-admin/StatusBadge";
import { Modal } from "@/components/super-admin/Modal";
import { ErrorState, EmptyState } from "@/components/super-admin/ErrorState";
import { Input } from "@/components/ui/Input";
import { PasswordInput } from "@/components/ui/PasswordInput";
import { Select } from "@/components/ui/Select";
import { Button } from "@/components/ui/Button";

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/[\s_]+/g, "-")
    .replace(/-+/g, "-")
    .slice(0, 63);
}

const TIMEZONE_OPTIONS = [
  { value: "Asia/Kolkata", label: "Asia/Kolkata (IST +05:30)" },
  { value: "UTC", label: "UTC (Coordinated Universal Time)" },
  { value: "America/New_York", label: "America/New_York (EST/EDT)" },
  { value: "America/Los_Angeles", label: "America/Los_Angeles (PST/PDT)" },
  { value: "Europe/London", label: "Europe/London (GMT/BST)" },
  { value: "Europe/Berlin", label: "Europe/Berlin (CET/CEST)" },
  { value: "Asia/Dubai", label: "Asia/Dubai (GST +04:00)" },
  { value: "Asia/Singapore", label: "Asia/Singapore (SGT +08:00)" },
  { value: "Asia/Tokyo", label: "Asia/Tokyo (JST +09:00)" },
];

const CURRENCY_OPTIONS = [
  { value: "INR", label: "INR (₹) - Indian Rupee" },
  { value: "USD", label: "USD ($) - US Dollar" },
  { value: "EUR", label: "EUR (€) - Euro" },
  { value: "GBP", label: "GBP (£) - British Pound" },
  { value: "AED", label: "AED (د.إ) - UAE Dirham" },
  { value: "SGD", label: "SGD (S$) - Singapore Dollar" },
];

export default function TenantsPage() {
  const [tenants, setTenants] = useState<TenantListItem[]>([]);
  const [meta, setMeta] = useState<PageMeta>({
    page: 1,
    limit: 20,
    total: 0,
    totalPages: 1,
  });
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Filters state
  const [searchTerm, setSearchTerm] = useState("");
  const [debouncedSearch, setDebouncedSearch] = useState("");
  const [statusFilter, setStatusFilter] = useState<string>("");
  const [planIdFilter, setPlanIdFilter] = useState<string>("");
  const [currentPage, setCurrentPage] = useState(1);
  const [pageSize, setPageSize] = useState(20);

  // Modal state
  const [isCreateModalOpen, setIsCreateModalOpen] = useState(false);
  const [createError, setCreateError] = useState<string | null>(null);
  const [createSuccess, setCreateSuccess] = useState<string | null>(null);
  const [isSlugAutoGenerated, setIsSlugAutoGenerated] = useState(true);

  // Debounce search input by 400ms
  const searchTimeoutRef = useRef<NodeJS.Timeout | null>(null);
  const handleSearchChange = (val: string) => {
    setSearchTerm(val);
    if (searchTimeoutRef.current) clearTimeout(searchTimeoutRef.current);
    searchTimeoutRef.current = setTimeout(() => {
      setDebouncedSearch(val);
      setCurrentPage(1);
    }, 400);
  };

  const fetchTenantsList = useCallback(async () => {
    setIsLoading(true);
    setError(null);

    try {
      const result = await getTenants({
        search: debouncedSearch || undefined,
        status: statusFilter || undefined,
        plan_id: planIdFilter || undefined,
        page: currentPage,
        limit: pageSize,
      });

      setTenants(result.tenants);
      setMeta(result.meta);
    } catch (err: unknown) {
      setError(parsePlatformError(err));
    } finally {
      setIsLoading(false);
    }
  }, [debouncedSearch, statusFilter, planIdFilter, currentPage, pageSize]);

  useEffect(() => {
    fetchTenantsList();
  }, [fetchTenantsList]);

  // Create Tenant Form
  const {
    register,
    handleSubmit,
    watch,
    setValue,
    reset,
    formState: { errors: formErrors, isSubmitting },
  } = useForm<CreateTenantFormData>({
    resolver: zodResolver(createTenantSchema),
    defaultValues: {
      name: "",
      slug: "",
      status: "TRIAL",
      timezone: "Asia/Kolkata",
      default_currency: "INR",
      plan_id: "",
      owner: {
        full_name: "",
        email: "",
        phone: "",
        password: "",
      },
    },
  });

  const tenantNameValue = watch("name");

  // Auto slug generator
  useEffect(() => {
    if (isSlugAutoGenerated && tenantNameValue) {
      setValue("slug", slugify(tenantNameValue), { shouldValidate: true });
    }
  }, [tenantNameValue, isSlugAutoGenerated, setValue]);

  const handleCreateSubmit = async (formData: CreateTenantFormData) => {
    setCreateError(null);
    setCreateSuccess(null);

    try {
      await createTenant({
        name: formData.name,
        slug: formData.slug,
        status: formData.status,
        timezone: formData.timezone,
        default_currency: formData.default_currency,
        plan_id: formData.plan_id || null,
        owner: {
          full_name: formData.owner.full_name,
          email: formData.owner.email,
          phone: formData.owner.phone || undefined,
          password: formData.owner.password || undefined,
        },
      });

      setCreateSuccess("Tenant and owner account provisioned successfully!");
      reset();
      setIsSlugAutoGenerated(true);

      setTimeout(() => {
        setIsCreateModalOpen(false);
        setCreateSuccess(null);
        fetchTenantsList();
      }, 1200);
    } catch (err: unknown) {
      setCreateError(parsePlatformError(err));
    }
  };

  return (
    <div className="space-y-6 max-w-7xl mx-auto animate-fadeIn">
      {/* Page Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-black text-slate-900 tracking-tight flex items-center gap-2">
            <Building2 className="h-6 w-6 text-indigo-600" />
            Tenants Management
          </h2>
          <p className="text-xs text-slate-500 mt-0.5">
            View, provision, and configure organizations across the platform.
          </p>
        </div>

        <Button
          variant="primary"
          size="md"
          onClick={() => {
            reset();
            setCreateError(null);
            setCreateSuccess(null);
            setIsSlugAutoGenerated(true);
            setIsCreateModalOpen(true);
          }}
          leftIcon={<Plus className="h-4 w-4" />}
          className="shadow-md shadow-indigo-600/20"
        >
          Create Tenant
        </Button>
      </div>

      {/* Filter and Search Bar */}
      <div className="rounded-2xl border border-slate-200 bg-white p-4 shadow-sm space-y-3">
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-12 gap-3 items-center">
          {/* Search Input */}
          <div className="lg:col-span-5 relative">
            <div className="pointer-events-none absolute inset-y-0 left-0 flex items-center pl-3 text-slate-400">
              <Search className="h-4 w-4" />
            </div>
            <input
              type="text"
              placeholder="Search by company name or slug..."
              value={searchTerm}
              onChange={(e) => handleSearchChange(e.target.value)}
              className="w-full rounded-lg border border-slate-300 bg-white pl-9 pr-3.5 py-2 text-xs text-slate-900 placeholder:text-slate-400 focus:outline-none focus:ring-4 focus:ring-indigo-500/10 focus:border-indigo-600 transition-all"
            />
          </div>

          {/* Status Filter Dropdown */}
          <div className="lg:col-span-3">
            <select
              value={statusFilter}
              onChange={(e) => {
                setStatusFilter(e.target.value);
                setCurrentPage(1);
              }}
              className="w-full rounded-lg border border-slate-300 bg-white px-3 py-2 text-xs text-slate-800 focus:outline-none focus:ring-4 focus:ring-indigo-500/10 focus:border-indigo-600"
            >
              <option value="">All Lifecycle Statuses</option>
              {TENANT_STATUSES.map((status) => (
                <option key={status} value={status}>
                  {status}
                </option>
              ))}
            </select>
          </div>

          {/* Plan Filter */}
          <div className="lg:col-span-3">
            <PlanSelect
              label=""
              placeholder="All Plans"
              includeAllOption
              allLabel="All Plans"
              value={planIdFilter}
              onChange={(val) => {
                setPlanIdFilter(val);
                setCurrentPage(1);
              }}
            />
          </div>

          {/* Reset Filters */}
          <div className="lg:col-span-1 flex justify-end">
            <Button
              size="sm"
              variant="outline"
              onClick={() => {
                setSearchTerm("");
                setDebouncedSearch("");
                setStatusFilter("");
                setPlanIdFilter("");
                setCurrentPage(1);
              }}
              className="w-full text-xs h-9 px-2"
              title="Reset all filters"
            >
              <RefreshCw className="h-3.5 w-3.5" />
            </Button>
          </div>
        </div>
      </div>

      {/* Error state */}
      {error && !isLoading && (
        <ErrorState
          title="Error Loading Tenants"
          message={error}
          onRetry={fetchTenantsList}
        />
      )}

      {/* Tenants Table */}
      <div className="rounded-2xl border border-slate-200 bg-white shadow-sm overflow-hidden">
        {isLoading ? (
          <div className="p-8 space-y-4 animate-pulse">
            <div className="h-8 bg-slate-100 rounded-lg w-full" />
            {Array.from({ length: 6 }).map((_, i) => (
              <div key={i} className="h-14 bg-slate-50 rounded-lg w-full" />
            ))}
          </div>
        ) : tenants.length > 0 ? (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="bg-slate-50 border-b border-slate-200 text-slate-500 uppercase tracking-wider font-semibold">
                <tr>
                  <th className="py-3.5 px-4">Company Name</th>
                  <th className="py-3.5 px-4">Workspace Slug</th>
                  <th className="py-3.5 px-4">Account Owner</th>
                  <th className="py-3.5 px-4">Status</th>
                  <th className="py-3.5 px-4">Timezone</th>
                  <th className="py-3.5 px-4">Currency</th>
                  <th className="py-3.5 px-4">Created Date</th>
                  <th className="py-3.5 px-4 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {tenants.map((tenant) => (
                  <tr
                    key={tenant.id}
                    className="hover:bg-slate-50/80 transition-colors group"
                  >
                    <td className="py-3.5 px-4 font-bold text-slate-900">
                      {tenant.name}
                    </td>
                    <td className="py-3.5 px-4 font-mono text-indigo-600">
                      {tenant.slug}.bizflow.app
                    </td>
                    <td className="py-3.5 px-4">
                      {tenant.owner ? (
                        <div>
                          <span className="block font-semibold text-slate-800">
                            {tenant.owner.full_name}
                          </span>
                          <span className="block text-[11px] text-slate-400">
                            {tenant.owner.email}
                          </span>
                        </div>
                      ) : (
                        <span className="text-slate-400 italic">No owner</span>
                      )}
                    </td>
                    <td className="py-3.5 px-4">
                      <StatusBadge status={tenant.status} />
                    </td>
                    <td className="py-3.5 px-4 text-slate-600 font-medium">
                      {tenant.timezone}
                    </td>
                    <td className="py-3.5 px-4">
                      <span className="inline-block px-1.5 py-0.5 rounded bg-slate-100 font-bold text-slate-700 text-[11px]">
                        {tenant.default_currency}
                      </span>
                    </td>
                    <td className="py-3.5 px-4 text-slate-500">
                      {tenant.created_at
                        ? new Date(tenant.created_at).toLocaleDateString()
                        : "-"}
                    </td>
                    <td className="py-3.5 px-4 text-right">
                      <Link href={`/super-admin/tenants/${tenant.id}`}>
                        <Button
                          size="sm"
                          variant="outline"
                          leftIcon={<Eye className="h-3.5 w-3.5" />}
                          className="h-8 text-xs font-semibold"
                        >
                          View
                        </Button>
                      </Link>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <EmptyState
            title="No Tenants Found"
            description="No tenants match your search query or filter criteria. Try adjusting filters or create a new tenant."
            action={
              <Button
                size="sm"
                variant="primary"
                onClick={() => setIsCreateModalOpen(true)}
                leftIcon={<Plus className="h-3.5 w-3.5" />}
              >
                Create New Tenant
              </Button>
            }
          />
        )}

        {/* Pagination Bar */}
        {meta.total > 0 && (
          <div className="flex flex-col sm:flex-row items-center justify-between gap-4 px-4 py-3.5 border-t border-slate-200 bg-slate-50/50 text-xs text-slate-600">
            <div className="flex items-center gap-2">
              <span>Rows per page:</span>
              <select
                value={pageSize}
                onChange={(e) => {
                  setPageSize(Number(e.target.value));
                  setCurrentPage(1);
                }}
                className="rounded border border-slate-300 bg-white px-2 py-1 text-xs focus:outline-none"
              >
                <option value={10}>10</option>
                <option value={20}>20</option>
                <option value={50}>50</option>
                <option value={100}>100</option>
              </select>
              <span className="text-slate-400">|</span>
              <span>
                Showing{" "}
                <span className="font-semibold text-slate-800">
                  {Math.min((meta.page - 1) * meta.limit + 1, meta.total)}
                </span>{" "}
                to{" "}
                <span className="font-semibold text-slate-800">
                  {Math.min(meta.page * meta.limit, meta.total)}
                </span>{" "}
                of <span className="font-semibold text-slate-800">{meta.total}</span>{" "}
                records
              </span>
            </div>

            <div className="flex items-center gap-2">
              <Button
                size="sm"
                variant="outline"
                disabled={currentPage <= 1 || isLoading}
                onClick={() => setCurrentPage((prev) => Math.max(prev - 1, 1))}
                className="h-8 text-xs px-2.5"
              >
                <ChevronLeft className="h-3.5 w-3.5 mr-1" />
                Previous
              </Button>
              <span className="font-bold text-slate-800 px-2">
                Page {meta.page} of {Math.max(meta.totalPages, 1)}
              </span>
              <Button
                size="sm"
                variant="outline"
                disabled={currentPage >= meta.totalPages || isLoading}
                onClick={() => setCurrentPage((prev) => Math.min(prev + 1, meta.totalPages))}
                className="h-8 text-xs px-2.5"
              >
                Next
                <ChevronRight className="h-3.5 w-3.5 ml-1" />
              </Button>
            </div>
          </div>
        )}
      </div>

      {/* Create Tenant Modal */}
      <Modal
        isOpen={isCreateModalOpen}
        onClose={() => setIsCreateModalOpen(false)}
        title="Provision New Tenant & Owner"
        description="Creates a dedicated tenant workspace, database schema, and initial owner user."
        maxWidth="2xl"
      >
        <form onSubmit={handleSubmit(handleCreateSubmit)} className="space-y-6" noValidate>
          {createError && (
            <div className="rounded-xl border border-rose-200 bg-rose-50 p-3.5 text-xs font-semibold text-rose-800 flex items-start gap-2">
              <AlertCircle className="h-4 w-4 shrink-0 text-rose-600 mt-0.5" />
              <div>{createError}</div>
            </div>
          )}

          {createSuccess && (
            <div className="rounded-xl border border-emerald-200 bg-emerald-50 p-3.5 text-xs font-semibold text-emerald-800 flex items-center gap-2">
              <CheckCircle2 className="h-4 w-4 text-emerald-600 shrink-0" />
              <div>{createSuccess}</div>
            </div>
          )}

          {/* Section 1: Tenant Information */}
          <div className="space-y-4">
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 border-b border-slate-100 pb-1.5 flex items-center gap-1.5">
              <Building2 className="h-3.5 w-3.5 text-indigo-600" />
              Workspace Configuration
            </h4>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <Input
                  label="Company Name"
                  required
                  placeholder="e.g. Nova Tech Pvt Ltd"
                  error={formErrors.name?.message}
                  {...register("name")}
                />
              </div>

              <div>
                <Input
                  label="Workspace URL Slug"
                  required
                  placeholder="nova-tech"
                  hint="Letters, numbers, and hyphens"
                  error={formErrors.slug?.message}
                  {...register("slug", {
                    onChange: () => setIsSlugAutoGenerated(false),
                  })}
                />
              </div>

              <div>
                <Select
                  label="Initial Status"
                  required
                  options={TENANT_STATUSES.map((s) => ({ value: s, label: s }))}
                  error={formErrors.status?.message}
                  {...register("status")}
                />
              </div>

              <div>
                <Select
                  label="Timezone"
                  required
                  options={TIMEZONE_OPTIONS}
                  error={formErrors.timezone?.message}
                  {...register("timezone")}
                />
              </div>

              <div>
                <Select
                  label="Default Currency"
                  required
                  options={CURRENCY_OPTIONS}
                  error={formErrors.default_currency?.message}
                  {...register("default_currency")}
                />
              </div>

              <div>
                <PlanSelect
                  label="Subscription Plan (Optional)"
                  placeholder="Select initial plan..."
                  value={watch("plan_id") || ""}
                  onChange={(val) => setValue("plan_id", val, { shouldValidate: true })}
                  error={formErrors.plan_id?.message}
                />
              </div>
            </div>
          </div>

          {/* Section 2: Owner Information */}
          <div className="space-y-4 pt-2">
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 border-b border-slate-100 pb-1.5 flex items-center gap-1.5">
              <User className="h-3.5 w-3.5 text-indigo-600" />
              Primary Owner Credentials
            </h4>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <Input
                  label="Owner Full Name"
                  required
                  placeholder="e.g. Amit Patel"
                  leftIcon={<User className="h-4 w-4" />}
                  error={formErrors.owner?.full_name?.message}
                  {...register("owner.full_name")}
                />
              </div>

              <div>
                <Input
                  label="Owner Email Address"
                  required
                  type="email"
                  placeholder="amit@novatech.in"
                  leftIcon={<Mail className="h-4 w-4" />}
                  error={formErrors.owner?.email?.message}
                  {...register("owner.email")}
                />
              </div>

              <div>
                <Input
                  label="Owner Phone Number (Optional)"
                  placeholder="+919876543210"
                  leftIcon={<Phone className="h-4 w-4" />}
                  error={formErrors.owner?.phone?.message}
                  {...register("owner.phone")}
                />
              </div>

              <div>
                <PasswordInput
                  label="Temporary Password (Optional)"
                  placeholder="Initial login password"
                  error={formErrors.owner?.password?.message}
                  {...register("owner.password")}
                />
              </div>
            </div>
          </div>

          {/* Modal Footer Actions */}
          <div className="flex items-center justify-end gap-3 pt-4 border-t border-slate-100">
            <Button
              type="button"
              variant="outline"
              size="md"
              onClick={() => setIsCreateModalOpen(false)}
              disabled={isSubmitting}
            >
              Cancel
            </Button>
            <Button
              type="submit"
              variant="primary"
              size="md"
              isLoading={isSubmitting}
            >
              Provision Workspace
            </Button>
          </div>
        </form>
      </Modal>
    </div>
  );
}
